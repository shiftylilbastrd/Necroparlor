def validate_setpoints(mode, values, critical_limits=None, range_margins=None):
    """Validate setpoint values coming from the web UI.
    Returns (cleaned_dict, None) on success or (None, error_message) on failure.
    `critical_limits` (notifications.critical_limits from the saved config)
    is optional - when given, the new setpoints must sit strictly inside
    them (see critical_limits_conflict), and with `range_margins` too, this
    mode's out-of-range band must as well (range_band_critical_conflict).
    The per-mode out-of-range margins that used to be validated here are
    gone - the margin is global now (notifications.range_margins); a saved
    mode still carrying the old keys just loses them on its next save,
    since this returns only the keys it knows.
    """
    if mode not in VALID_MODES:
        return None, f"Unknown mode '{mode}'"
    try:
        low = float(values["low_temp_f"])
        high = float(values["high_temp_f"])
        humidity = float(values["humidity_setpoint"])
    except (KeyError, TypeError, ValueError):
        return None, "low_temp_f, high_temp_f and humidity_setpoint are required numbers"

    if not (TEMP_BOUNDS_F[0] <= low <= TEMP_BOUNDS_F[1]):
        return None, f"low_temp_f must be between {TEMP_BOUNDS_F[0]} and {TEMP_BOUNDS_F[1]}"
    if not (TEMP_BOUNDS_F[0] <= high <= TEMP_BOUNDS_F[1]):
        return None, f"high_temp_f must be between {TEMP_BOUNDS_F[0]} and {TEMP_BOUNDS_F[1]}"
    if low >= high:
        return None, "low_temp_f must be less than high_temp_f"
    if not (HUMIDITY_BOUNDS[0] <= humidity <= HUMIDITY_BOUNDS[1]):
        return None, f"humidity_setpoint must be between {HUMIDITY_BOUNDS[0]} and {HUMIDITY_BOUNDS[1]}"

    cleaned = {"low_temp_f": low, "high_temp_f": high, "humidity_setpoint": humidity}

    if critical_limits is not None:
        error = critical_limits_conflict(critical_limits, {mode: cleaned})
        if error:
            return None, error
    if critical_limits is not None and range_margins is not None:
        error = range_band_critical_conflict(range_margins, critical_limits, {mode: cleaned})
        if error:
            return None, error

    if mode == "cleaning":
        try:
            interval = int(values.get("vent_interval_minutes", 30))
            duration = int(values.get("vent_duration_minutes", 5))
        except (TypeError, ValueError):
            return None, "vent_interval_minutes and vent_duration_minutes must be integers"
        if not (VENT_INTERVAL_BOUNDS[0] <= interval <= VENT_INTERVAL_BOUNDS[1]):
            return None, (f"vent_interval_minutes must be between "
                           f"{VENT_INTERVAL_BOUNDS[0]} and {VENT_INTERVAL_BOUNDS[1]}")
        if not (VENT_DURATION_BOUNDS[0] <= duration <= VENT_DURATION_BOUNDS[1]):
            return None, (f"vent_duration_minutes must be between "
                           f"{VENT_DURATION_BOUNDS[0]} and {VENT_DURATION_BOUNDS[1]}")
        if duration >= interval:
            return None, "vent_duration_minutes should be shorter than vent_interval_minutes"
        cleaned["vent_interval_minutes"] = interval
        cleaned["vent_duration_minutes"] = duration

    # [2026-10-16] snapshot_interval_minutes is no longer a per-mode
    # setting - timelapse capture belongs to recordings now (see the
    # "Timelapse RECORDINGS" section). An old page still sending it is
    # simply ignored, and a saved mode drops the key on its next save.

    return cleaned, None


def validate_history_retention(days):
    """Validates the Settings page's "Keep sensor readings & event log
    for (days)" field. Returns (days, None) on success or (None,
    error_message) on failure - same two-tuple shape as
    validate_setpoints above, just for a single bare value instead of a
    dict, since that's all this one setting is. 0 means "keep
    everything forever" and is deliberately exempt from
    HISTORY_RETENTION_BOUNDS, same never-sentinel convention as
    snapshot_interval_minutes."""
    try:
        days = int(days)
    except (TypeError, ValueError):
        return None, "days must be a whole number"
    if days != 0 and not (HISTORY_RETENTION_BOUNDS[0] <= days <= HISTORY_RETENTION_BOUNDS[1]):
        return None, (f"days must be 0 (forever) or between "
                       f"{HISTORY_RETENTION_BOUNDS[0]} and {HISTORY_RETENTION_BOUNDS[1]}")
    return days, None


