def log_event(level, message, category=None):
    """Records a state-change/alarm event to SQLite AND to the Python
    logging module, so it shows up in both the dashboard event log and
    the on-disk log file. `category` is optional - see EVENT_CATEGORIES
    above - and, when given, is what lets a warning/error/critical event
    be individually muted from the Notifications card without raising
    min_level and losing every OTHER category at that severity too.

    Also the single choke point that decides whether this event should
    trigger an outbound notification (Pushover/email/webhook) - see
    _maybe_notify() below. Deliberately wrapped in its own try/except
    here rather than left to propagate: a bug in the notification path
    must never prevent the event itself from being recorded, which is
    the one thing every single caller across this project actually
    depends on log_event() for."""
    conn = get_db()
    conn.execute("INSERT INTO events VALUES (?,?,?,?)", (time.time(), level, message, category))
    conn.commit()
    conn.close()
    getattr(logging, level.lower(), logging.info)(message)
    try:
        _maybe_notify(level, message, category)
    except Exception:
        logging.exception("Notification dispatch check failed (event above was still logged normally)")


# --------------------------------------------------------------------------
# Outbound notifications (Pushover / email / generic webhook)
# --------------------------------------------------------------------------
# Fired from log_event() above for anything at or above notifications.
# min_level, gated by the per-category toggle (when a category was
# given), quiet hours, and a per-category cooldown - see DEFAULT_CONFIG's
# "notifications" block for what each setting means.
#
# The actual network call (Pushover HTTP POST / SMTP / webhook HTTP
# POST) never runs on the caller's thread. climate.py's control loop has
# a fixed LOOP_INTERVAL cadence that sensor reads and relay timing both
# depend on - stalling it for however long an unreachable Pushover API
# or a slow SMTP handshake takes would turn a notification problem into
# a climate control problem, which is strictly worse. A tiny background
# worker thread + queue absorbs that; log_event() only ever enqueues.
_notify_queue = queue.Queue()
_notify_thread_lock = threading.Lock()
_notify_thread_started = False

# Per-category (or, for an uncategorized call, per-message) last-sent
# timestamp, in-memory only - NOT persisted to config.json or the DB.
# Deliberate: this state resets on every process restart, which means a
# climate.py restart right after a real alert can re-notify immediately
# even if it's within the configured cooldown window. That's the correct
# failure mode here, not a bug to fix later - a process that just
# restarted (possibly BECAUSE of whatever tripped the alert) is exactly
# when you most want to know if the same condition is still true, not
# when a stale in-memory cooldown should stay silent about it.
_notify_last_sent = {}
_notify_state_lock = threading.Lock()

NOTIFY_HTTP_TIMEOUT_SECONDS = 10
NOTIFY_SMTP_TIMEOUT_SECONDS = 10


def _ensure_notify_thread():
    """Lazily starts the background dispatch thread on first use, not at
    import time - shared_state.py is imported by one-off helper scripts
    too (discover_ble_sensor.py, discover_camera.py) that call
    log_event() rarely or never; those shouldn't gain a permanent
    background thread just for importing this module."""
    global _notify_thread_started
    if _notify_thread_started:
        return
    with _notify_thread_lock:
        if _notify_thread_started:
            return
        threading.Thread(target=_notify_worker, daemon=True).start()
        _notify_thread_started = True


def _notify_worker():
    """Runs for the life of the process, pulling queued (level, message)
    pairs and actually sending them. Any exception sending to one channel
    must not stop the others, or stop this loop from picking up the next
    queued item - see _send_all_channels below."""
    while True:
        level, message = _notify_queue.get()
        try:
            _send_all_channels(level, message)
        except Exception:
            logging.exception("Notification dispatch failed")


def _in_quiet_hours(quiet_hours):
    """quiet_hours: the "quiet_hours" sub-dict (enabled/start/end).
    Handles a window that wraps midnight (e.g. 22:00-07:00) as well as
    one that doesn't (e.g. 09:00-17:00, if someone wants the OPPOSITE of
    quiet hours by naming a daytime-only window instead)."""
    if not quiet_hours.get("enabled"):
        return False
    now = datetime.now(LOCAL_TZ).strftime("%H:%M")
    start, end = quiet_hours["start"], quiet_hours["end"]
    if start <= end:
        return start <= now < end
    return now >= start or now < end   # wraps midnight


def _passes_cooldown(cooldown_minutes, key):
    """key: the category id, or (for an uncategorized event) the message
    text itself - either way, the thing that has to repeat before this
    gate suppresses it again. Returns True (and records `now` as the new
    last-sent time) if this key hasn't notified within cooldown_minutes;
    False if it's still within the window."""
    if cooldown_minutes <= 0:
        return True
    now = time.time()
    with _notify_state_lock:
        last = _notify_last_sent.get(key)
        if last is not None and (now - last) < cooldown_minutes * 60:
            return False
        _notify_last_sent[key] = now
        return True


def _maybe_notify(level, message, category):
    """The gate log_event() calls on every write - checks enabled,
    min_level, the per-category toggle (when categorized), quiet hours,
    and cooldown, in that order (cheapest/most-likely-to-reject checks
    first), before actually enqueueing anything for _notify_worker."""
    config = load_config().get("notifications", DEFAULT_CONFIG["notifications"])
    if not config.get("enabled"):
        return
    min_level = config.get("min_level", "warning")
    if EVENT_LEVELS.index(level) < EVENT_LEVELS.index(min_level):
        return
    if category in EVENT_CATEGORIES and not config.get("categories", {}).get(category, True):
        return
    quiet_hours = config.get("quiet_hours", {})
    if _in_quiet_hours(quiet_hours) and not (level == "critical" and quiet_hours.get("allow_critical", True)):
        return
    if not _passes_cooldown(config.get("cooldown_minutes", 15), category or message):
        return
    _ensure_notify_thread()
    _notify_queue.put((level, message))


def _send_all_channels(level, message, config=None):
    """Sends through every ENABLED channel in `config` (or the live
    saved config, if not given - see send_test_notification() below for
    why a caller would pass one explicitly). Each channel's own failure
    is caught and logged via the plain `logging` module, deliberately
    NOT via log_event() - a failed notification calling log_event() would
    itself be notification-worthy by the same rule that got it here,
    which is exactly the infinite-recursion trap this avoids. Returns a
    per-channel {ok, error} dict so the Config page's "Send test" button
    can show which channel(s), if any, actually failed."""
    if config is None:
        config = load_config().get("notifications", DEFAULT_CONFIG["notifications"])
    channels = config.get("channels", {})
    results = {}
    title = f"Necroparlor [{level.upper()}]"

    pushover = channels.get("pushover", {})
    if pushover.get("enabled"):
        ok, error = _send_pushover(pushover, level, title, message)
        results["pushover"] = {"ok": ok, "error": error}
        if not ok:
            logging.error(f"Pushover notification failed: {error}")

    email = channels.get("email", {})
    if email.get("enabled"):
        ok, error = _send_email(email, title, message)
        results["email"] = {"ok": ok, "error": error}
        if not ok:
            logging.error(f"Email notification failed: {error}")

    webhook = channels.get("webhook", {})
    if webhook.get("enabled"):
        ok, error = _send_webhook(webhook, level, message)
        results["webhook"] = {"ok": ok, "error": error}
        if not ok:
            logging.error(f"Webhook notification failed: {error}")

    return results


def _send_pushover(cfg, level, title, message):
    """https://pushover.net/api - a single form-encoded POST, no SDK
    needed. priority=1 ("high priority") for critical bypasses the
    recipient's device quiet hours on Pushover's own side too and
    requires acknowledgment-style delivery; ordinary priority (0) for
    everything else."""
    data = urllib.parse.urlencode({
        "token": cfg.get("api_token", ""),
        "user": cfg.get("user_key", ""),
        "title": title,
        "message": message,
        "priority": 1 if level == "critical" else 0,
    }).encode()
    req = urllib.request.Request("https://api.pushover.net/1/messages.json", data=data)
    try:
        with urllib.request.urlopen(req, timeout=NOTIFY_HTTP_TIMEOUT_SECONDS) as resp:
            if resp.status == 200:
                return True, None
            return False, f"HTTP {resp.status}"
    except urllib.error.HTTPError as e:
        body = e.read().decode(errors="replace")[:300]
        return False, f"HTTP {e.code}: {body}"
    except (urllib.error.URLError, OSError) as e:
        return False, str(e)


def _send_email(cfg, subject, message):
    """Plain smtplib - no third-party dependency needed for a single
    outbound message. use_tls uses STARTTLS on the given port (587 is
    the conventional submission port for this); a bare SSL connection on
    465 isn't offered as a separate option since STARTTLS-on-587 covers
    every mainstream provider (Gmail app passwords included) this
    project is realistically configured against."""
    try:
        msg = MIMEText(message)
        msg["Subject"] = subject
        msg["From"] = cfg.get("from_addr", "")
        msg["To"] = cfg.get("to_addr", "")
        with smtplib.SMTP(cfg.get("smtp_host", ""), cfg.get("smtp_port", 587),
                           timeout=NOTIFY_SMTP_TIMEOUT_SECONDS) as smtp:
            if cfg.get("use_tls", True):
                smtp.starttls()
            if cfg.get("smtp_user"):
                smtp.login(cfg["smtp_user"], cfg.get("smtp_password", ""))
            smtp.sendmail(cfg.get("from_addr", ""), [cfg.get("to_addr", "")], msg.as_string())
        return True, None
    except (smtplib.SMTPException, OSError, TimeoutError) as e:
        return False, str(e)


def _send_webhook(cfg, level, message):
    """POSTs a small JSON payload to an arbitrary URL - a self-rolled
    endpoint, ntfy.sh, Home Assistant's webhook trigger, etc. can all
    read whatever fields they want out of the generic level/message/ts/
    source shape below, so this doesn't try to guess which specific
    service is on the other end.

    Discord and Slack incoming webhooks are the two most likely targets
    though (per the Config page's own description of this card), and
    BOTH have a real, enforced payload requirement, not just a
    convention: Discord rejects a body with no "content" (or "embeds"/
    "components"), and Slack's classic incoming webhooks expect "text" -
    an arbitrary JSON body would otherwise pass this function's own
    success check (a 2xx from Cloudflare) while never actually showing
    up as a message. `content`/`text` are added alongside the generic
    fields so this works out of the box against either one without
    special-casing which service is configured - both silently ignore
    JSON keys they don't recognize.

    A custom User-Agent is required, not just polite - Discord's
    Cloudflare front door blocks the default `Python-urllib/3.x` UA
    outright (HTTP 403, Cloudflare error 1010, "blocked based on your
    browser's signature") before the request ever reaches Discord's own
    webhook handler. Worth remembering if this ever gets ported to a
    different HTTP client - the same default-UA block applies there
    too, it's Cloudflare's WAF rejecting the request, not anything
    specific to urllib."""
    text = f"Necroparlor [{level.upper()}]: {message}"
    payload = json.dumps({
        "source": "Necroparlor",
        "level": level,
        "message": message,
        "ts": time.time(),
        "content": text,  # Discord
        "text": text,     # Slack (classic incoming webhooks)
    }).encode()
    req = urllib.request.Request(
        cfg.get("url", ""), data=payload,
        headers={
            "Content-Type": "application/json",
            "User-Agent": "Necroparlor/1.0 (+https://github.com/shiftylilbastrd/Necroparlor)",
        },
        method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=NOTIFY_HTTP_TIMEOUT_SECONDS) as resp:
            if 200 <= resp.status < 300:
                return True, None
            return False, f"HTTP {resp.status}"
    except urllib.error.HTTPError as e:
        body = e.read().decode(errors="replace")[:300]
        return False, f"HTTP {e.code}: {body}"
    except (urllib.error.URLError, OSError) as e:
        return False, str(e)


TEST_NOTIFICATION_TITLE = "Necroparlor [TEST]"
TEST_NOTIFICATION_MESSAGE = "Test notification from Necroparlor - if you got this, it's configured correctly."


def send_test_notification(channel=None, channel_config=None):
    """Sends a one-off test message right now - either through every
    SAVED+enabled channel at once (channel=None, the General card's
    "Send test" button), or through exactly one channel in isolation
    (channel="pushover"/"email"/"webhook", each channel card's own
    "Send test" button next to it).

    Either way this bypasses notifications.enabled/min_level/category
    toggles/quiet hours/cooldown entirely - none of those should stand
    between "I just typed in a Pushover token" and finding out
    immediately whether it actually works.

    The channel=None path still only sends through whichever channel(s)
    are individually enabled, using whatever's currently SAVED in
    config.json - Save must happen before Send test there, same as every
    other Config page card in this project.

    The single-channel path is different on purpose: `channel_config`,
    when given, is whatever's currently TYPED into that one card -
    unsaved, and NOT required to have "Enabled" checked - since the
    whole point of a per-channel test button is checking a token/
    password/URL before committing to Save. That channel is always
    treated as enabled for this one test, regardless of what the
    checkbox says. Falls back to the saved config for that channel if
    `channel_config` isn't given (e.g. testing a channel that's already
    saved without changing anything first).

    Returns a {channel_id: {ok, error}} dict either way, so the Config
    page's JS doesn't need two different response shapes to handle."""
    if channel is not None:
        if channel not in ("pushover", "email", "webhook"):
            return {channel: {"ok": False, "error": f"Unknown channel '{channel}'"}}
        if channel_config is None:
            saved = load_config().get("notifications", DEFAULT_CONFIG["notifications"])
            channel_config = saved.get("channels", {}).get(channel, {})
        cfg = {**channel_config, "enabled": True}
        if channel == "pushover":
            ok, error = _send_pushover(cfg, "info", TEST_NOTIFICATION_TITLE, TEST_NOTIFICATION_MESSAGE)
        elif channel == "email":
            ok, error = _send_email(cfg, TEST_NOTIFICATION_TITLE, TEST_NOTIFICATION_MESSAGE)
        else:
            ok, error = _send_webhook(cfg, "info", TEST_NOTIFICATION_MESSAGE)
        return {channel: {"ok": ok, "error": error}}

    config = load_config().get("notifications", DEFAULT_CONFIG["notifications"])
    return _send_all_channels("info", TEST_NOTIFICATION_MESSAGE, config=config)


def get_last_valid_timestamps():
    """For each tile's metric, when did it last actually have a valid
    (non-null) reading - not just when the most recent row was written.
    A tile's value can go null for a cycle or several (a failed read, a
    stale external source) while the row itself keeps getting written -
    this is what lets the dashboard show a genuine per-tile 'last
    updated' time instead of implying every tile refreshed just because
    /api/status was polled again.

    Limited to the last 24h so this stays a cheap, fast query regardless
    of how large the readings table eventually grows - a metric with no
    valid reading in the last 24h is already extremely stale, so there's
    no need to scan further back to say so.
    """
    conn = get_db()
    since = time.time() - 86400
    row = conn.execute(
        """
        SELECT MAX(CASE WHEN internal_temp IS NOT NULL THEN ts END),
               MAX(CASE WHEN ble_temp IS NOT NULL THEN ts END),
               MAX(CASE WHEN wired_temp IS NOT NULL THEN ts END)
        FROM readings
        WHERE ts >= ?
        """,
        (since,)
    ).fetchone()
    conn.close()
    return {"internal": row[0], "ble": row[1], "wired": row[2]}


def get_latest_reading():
    conn = get_db()
    row = conn.execute(
        "SELECT ts, mode, internal_temp, internal_humidity, external_temp, external_humidity, "
        "fan, heater, dehumidifier, vent, ble_temp, ble_humidity, wired_temp, wired_humidity, "
        "active_external_source, cpu_temp_f, cpu_load_1m FROM readings ORDER BY ts DESC LIMIT 1"
    ).fetchone()
    conn.close()
    if not row:
        return None
    keys = ["ts", "mode", "internal_temp", "internal_humidity", "external_temp", "external_humidity",
            "fan", "heater", "dehumidifier", "vent", "ble_temp", "ble_humidity", "wired_temp", "wired_humidity",
            "active_external_source", "cpu_temp_f", "cpu_load_1m"]
    return dict(zip(keys, row))


def _local_utc_offset_seconds():
    """Current UTC offset for LOCAL_TZ, in seconds (negative for zones
    west of UTC, e.g. -25200 for Pacific Daylight). Recomputed on every
    call rather than cached, so it's automatically correct across DST
    transitions without needing a service restart."""
    return int(datetime.now(LOCAL_TZ).utcoffset().total_seconds())


def get_history(hours):
    """Returns downsampled time-series points covering the last `hours`
    hours, bucketed/averaged so long ranges don't ship huge numbers of
    rows to the browser. Each metric also carries its min/max within the
    bucket, for a mean-with-band chart (like Home Assistant's Statistics
    Graph card) - bands are naturally near-zero width when a bucket only
    holds one raw reading and widen when it holds several, exactly
    reflecting real variance, not a fabricated effect.

    Bucket size is a fixed, human-meaningful interval per range tier
    (matching the dashboard's four range buttons) rather than a sliding
    point-count target - so the chart's grid lines land on predictable
    boundaries (every 15 min, every hour, etc.) at every zoom level
    instead of some arbitrary in-between spacing.

    Boundaries are anchored to LOCAL midnight, not UTC midnight: readings
    are stored as raw UTC epoch seconds, and naively flooring those to a
    bucket size gives boundaries that land on UTC-clean-but-locally-odd
    clock times (e.g. a 6h bucket edge at UTC midnight is 5pm the
    previous day in Pacific time - not a clean local hour at all). Each
    timestamp is shifted into local-equivalent seconds before bucketing,
    then shifted back so the returned value is still a valid UTC epoch
    the frontend can display correctly - the net effect is that an 8h
    bucket's edges land on local 12am/6am/12pm/6pm rather than an arbitrary
    UTC-derived local time.
    """
    conn = get_db()
    since = time.time() - hours * 3600
    if hours <= 1:
        bucket_seconds = 2 * 60            # 1h view  -> 2-minute buckets
    elif hours <= 6:
        bucket_seconds = 15 * 60          # 6h view  -> 15-minute buckets
    elif hours <= 24:
        bucket_seconds = 60 * 60          # 24h view -> 1-hour buckets
    elif hours <= 168:
        bucket_seconds = 6 * 60 * 60       # 7d view  -> 6-hour buckets
    else:
        bucket_seconds = 24 * 60 * 60     # 30d view -> 1-day buckets
    offset = _local_utc_offset_seconds()
    rows = conn.execute(
        """
        SELECT CAST((ts + ?) / ? AS INTEGER) * ? - ? AS bucket,
               AVG(internal_temp), MIN(internal_temp), MAX(internal_temp),
               AVG(internal_humidity), MIN(internal_humidity), MAX(internal_humidity),
               AVG(ble_temp), MIN(ble_temp), MAX(ble_temp),
               AVG(ble_humidity), MIN(ble_humidity), MAX(ble_humidity),
               AVG(wired_temp), MIN(wired_temp), MAX(wired_temp),
               AVG(wired_humidity), MIN(wired_humidity), MAX(wired_humidity)
        FROM readings
        WHERE ts >= ?
        GROUP BY bucket
        ORDER BY bucket ASC
        """,
        (offset, bucket_seconds, bucket_seconds, offset, since)
    ).fetchall()
    conn.close()
    return [
        {
            "ts": r[0],
            "internal_temp": r[1], "internal_temp_min": r[2], "internal_temp_max": r[3],
            "internal_humidity": r[4], "internal_humidity_min": r[5], "internal_humidity_max": r[6],
            "ble_temp": r[7], "ble_temp_min": r[8], "ble_temp_max": r[9],
            "ble_humidity": r[10], "ble_humidity_min": r[11], "ble_humidity_max": r[12],
            "wired_temp": r[13], "wired_temp_min": r[14], "wired_temp_max": r[15],
            "wired_humidity": r[16], "wired_humidity_min": r[17], "wired_humidity_max": r[18],
        }
        for r in rows
    ]


