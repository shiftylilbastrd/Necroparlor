# Registry of supported BLE sensor brands for the passive listener
# (ble_listener.py). Each entry names a PyPI package and the class
# within it that decodes that brand's advertisement format - all of
# these share the same interface (a BluetoothData subclass with a
# .update(service_info) method returning .entity_values), since
# they're siblings in the same open-source ecosystem Home Assistant
# uses for its native Bluetooth integrations. Adding a new brand is
# usually just: pip install <package>, then one line here.
#
# Confidence varies by entry - "sensorpush", "inkbird", and "govee"
# were directly confirmed against real source/usage examples; others
# follow the same well-established naming convention across this
# ecosystem but weren't individually verified. If a brand's class name
# has changed or is different than listed, ble_listener.py will fail
# with a clear ImportError naming the exact package/class it tried,
# not a silent failure - check that brand's PyPI page if so.
BLE_SENSOR_LIBRARIES = {
    "sensorpush": {"package": "sensorpush_ble", "class": "SensorPushBluetoothDeviceData", "label": "SensorPush"},
    "govee": {"package": "govee_ble", "class": "GoveeBluetoothDeviceData", "label": "Govee"},
    "inkbird": {"package": "inkbird_ble", "class": "INKBIRDBluetoothDeviceData", "label": "INKBIRD"},
    "xiaomi": {"package": "xiaomi_ble", "class": "XiaomiBluetoothDeviceData", "label": "Xiaomi"},
    "ruuvitag": {"package": "ruuvitag_ble", "class": "RuuviTagBluetoothDeviceData", "label": "RuuviTag"},
}


def validate_ble_mac(ble_mac):
    """Validates a BLE sensor address for saving - identifies which
    physical unit to listen for, not a mode toggle (external source
    selection is automatic failover, not manual). Returns (mac, None)
    on success or (None, error) on failure. An empty value is allowed -
    it just means no BLE sensor is configured, so climate.py always
    uses the wired probe until one is set."""
    if not ble_mac:
        return None, None
    if not MAC_ADDRESS_RE.match(ble_mac):
        return None, "ble_mac must look like AA:BB:CC:DD:EE:FF"
    return ble_mac.upper(), None


def validate_ble_sensor_type(sensor_type):
    """Validates a BLE sensor brand selection against the supported
    registry above. Returns (sensor_type, None) on success or
    (None, error) on failure."""
    if sensor_type not in BLE_SENSOR_LIBRARIES:
        return None, f"ble_sensor_type must be one of {sorted(BLE_SENSOR_LIBRARIES)}"
    return sensor_type, None



def validate_camera_settings(values):
    """Validates the USB webcam device/resolution/camera-streamer-port
    settings for saving. Returns (cleaned_dict, None) on success or
    (None, error) on failure. Deliberately doesn't try to open the
    device or contact camera-streamer to confirm either actually works -
    this just sanity-checks the shape of the input; camera-streamer logs
    its own error if the configured device can't be opened, the same way
    camera_service.py used to before the 2026-09-14 camera-streamer
    switch (see docs/camera-streamer-setup.md)."""
    device = values.get("device", "0")
    if not isinstance(device, str) or not CAMERA_DEVICE_RE.match(device):
        return None, "device must be a device index (e.g. '0') or a /dev path"
    try:
        width = int(values.get("width", 1280))
        height = int(values.get("height", 720))
    except (TypeError, ValueError):
        return None, "width and height must be whole numbers"
    try:
        streamer_port = int(values.get("streamer_port", 8090))
    except (TypeError, ValueError):
        return None, "streamer_port must be a whole number"
    if not (CAMERA_WIDTH_BOUNDS[0] <= width <= CAMERA_WIDTH_BOUNDS[1]):
        return None, f"width must be between {CAMERA_WIDTH_BOUNDS[0]} and {CAMERA_WIDTH_BOUNDS[1]}"
    if not (CAMERA_HEIGHT_BOUNDS[0] <= height <= CAMERA_HEIGHT_BOUNDS[1]):
        return None, f"height must be between {CAMERA_HEIGHT_BOUNDS[0]} and {CAMERA_HEIGHT_BOUNDS[1]}"
    if streamer_port == CAMERA_STREAMER_FORBIDDEN_PORT:
        return None, (f"streamer_port can't be {CAMERA_STREAMER_FORBIDDEN_PORT} - "
                       "that's webapp.py's own port")
    if not (CAMERA_STREAMER_PORT_BOUNDS[0] <= streamer_port <= CAMERA_STREAMER_PORT_BOUNDS[1]):
        return None, (f"streamer_port must be between "
                       f"{CAMERA_STREAMER_PORT_BOUNDS[0]} and {CAMERA_STREAMER_PORT_BOUNDS[1]}")
    return {
        "device": device,
        "width": width,
        "height": height,
        "streamer_port": streamer_port,
    }, None


def write_camera_streamer_env(cam_cfg):
    """Regenerates camera-streamer.env (see CAMERA_STREAMER_ENV_PATH
    above) from config.json's "camera" settings - the bridge between the
    Config page's Camera card and systemd/camera-streamer.service's
    EnvironmentFile=. Called by webapp.py's api_set_camera_settings()
    every time that card is saved, right before the service is
    restarted, so the restart actually picks up the new values.

    CAMERA_PATH is a real /dev/videoN path rather than passing a bare
    index straight through - camera-streamer's own USB example
    (tools/usb_camera.sh, see docs/camera-streamer-setup.md) expects a
    device path, not an index. A bare numeric device ("0") is converted;
    an already-a-path device (a by-id symlink) is passed through as-is.

    Atomic write (write-tmp-then-rename), same as config.json/the live
    frame used to be - camera-streamer reads this at its own startup via
    systemd's EnvironmentFile=, not continuously, so there's no reader
    that could observe a half-written file in practice, but it costs
    nothing to be consistent with this project's other shared files."""
    device = cam_cfg.get("device", "0")
    camera_path = f"/dev/video{device}" if device.isdigit() else device
    lines = [
        f"CAMERA_PATH={camera_path}",
        f"CAMERA_WIDTH={cam_cfg.get('width', 1280)}",
        f"CAMERA_HEIGHT={cam_cfg.get('height', 720)}",
        f"CAMERA_STREAMER_PORT={cam_cfg.get('streamer_port', 8090)}",
    ]
    _atomic_write(CAMERA_STREAMER_ENV_PATH, "\n".join(lines) + "\n")


def validate_notification_settings(values):
    """Validates the whole "notifications" block coming from the Config
    page's Notifications card. Returns (cleaned_dict, None) on success or
    (None, error) on failure - same shape as validate_camera_settings
    above. Deliberately does NOT try to contact Pushover/SMTP/the webhook
    URL to confirm credentials actually work - that's what the Config
    page's "Send test" button (send_test_notification() below) is for;
    this just sanity-checks the shape of the input so a typo doesn't
    silently corrupt config.json's notifications block."""
    cleaned = {"enabled": bool(values.get("enabled", False))}

    min_level = values.get("min_level", "warning")
    if min_level not in EVENT_LEVELS:
        return None, f"min_level must be one of {EVENT_LEVELS}"
    cleaned["min_level"] = min_level

    categories = values.get("categories", {})
    cleaned["categories"] = {
        cat: bool(categories.get(cat, True)) for cat in EVENT_CATEGORIES
    }

    try:
        cooldown = int(values.get("cooldown_minutes", 15))
    except (TypeError, ValueError):
        return None, "cooldown_minutes must be a whole number"
    if not (NOTIFY_COOLDOWN_BOUNDS[0] <= cooldown <= NOTIFY_COOLDOWN_BOUNDS[1]):
        return None, (f"cooldown_minutes must be between "
                       f"{NOTIFY_COOLDOWN_BOUNDS[0]} and {NOTIFY_COOLDOWN_BOUNDS[1]}")
    cleaned["cooldown_minutes"] = cooldown

    try:
        door_minutes = int(values.get("door_open_alert_minutes", 15))
    except (TypeError, ValueError):
        return None, "door_open_alert_minutes must be a whole number"
    if door_minutes != 0 and not (DOOR_OPEN_ALERT_BOUNDS[0] <= door_minutes <= DOOR_OPEN_ALERT_BOUNDS[1]):
        return None, (f"door_open_alert_minutes must be 0 (never) or between "
                       f"{DOOR_OPEN_ALERT_BOUNDS[0]} and {DOOR_OPEN_ALERT_BOUNDS[1]}")
    cleaned["door_open_alert_minutes"] = door_minutes

    qh = values.get("quiet_hours", {})
    start = qh.get("start", "22:00")
    end = qh.get("end", "07:00")
    if not QUIET_HOURS_TIME_RE.match(start):
        return None, "quiet_hours.start must look like HH:MM (24h)"
    if not QUIET_HOURS_TIME_RE.match(end):
        return None, "quiet_hours.end must look like HH:MM (24h)"
    cleaned["quiet_hours"] = {
        "enabled": bool(qh.get("enabled", False)),
        "start": start,
        "end": end,
        "allow_critical": bool(qh.get("allow_critical", True)),
    }

    channels = values.get("channels", {})

    pushover = channels.get("pushover", {})
    cleaned_pushover = {
        "enabled": bool(pushover.get("enabled", False)),
        "api_token": str(pushover.get("api_token", "")).strip(),
        "user_key": str(pushover.get("user_key", "")).strip(),
    }
    if cleaned_pushover["enabled"] and not (cleaned_pushover["api_token"] and cleaned_pushover["user_key"]):
        return None, "Pushover is enabled but api_token/user_key are missing"

    email = channels.get("email", {})
    try:
        smtp_port = int(email.get("smtp_port", 587))
    except (TypeError, ValueError):
        return None, "email.smtp_port must be a whole number"
    if not (SMTP_PORT_BOUNDS[0] <= smtp_port <= SMTP_PORT_BOUNDS[1]):
        return None, f"email.smtp_port must be between {SMTP_PORT_BOUNDS[0]} and {SMTP_PORT_BOUNDS[1]}"
    cleaned_email = {
        "enabled": bool(email.get("enabled", False)),
        "smtp_host": str(email.get("smtp_host", "")).strip(),
        "smtp_port": smtp_port,
        "use_tls": bool(email.get("use_tls", True)),
        "smtp_user": str(email.get("smtp_user", "")).strip(),
        # An empty incoming password means "leave whatever's already
        # saved alone" (see api_set_notification_settings in webapp.py) -
        # by the time it gets here it's already been filled back in from
        # the existing config if left blank, so this function never has
        # to special-case "enabled but no password" itself.
        "smtp_password": str(email.get("smtp_password", "")),
        "from_addr": str(email.get("from_addr", "")).strip(),
        "to_addr": str(email.get("to_addr", "")).strip(),
    }
    if cleaned_email["enabled"] and not (cleaned_email["smtp_host"] and cleaned_email["from_addr"]
                                          and cleaned_email["to_addr"]):
        return None, "Email is enabled but smtp_host/from_addr/to_addr are missing"

    webhook = channels.get("webhook", {})
    cleaned_webhook = {
        "enabled": bool(webhook.get("enabled", False)),
        "url": str(webhook.get("url", "")).strip(),
    }
    if cleaned_webhook["enabled"] and not cleaned_webhook["url"].startswith(("http://", "https://")):
        return None, "Webhook is enabled but url must start with http:// or https://"

    cleaned["channels"] = {"pushover": cleaned_pushover, "email": cleaned_email, "webhook": cleaned_webhook}
    return cleaned, None


CALIBRATION_KEYS = (
    "internal_temp_offset", "internal_humidity_offset",
    "ble_temp_offset", "ble_humidity_offset",
    "wired_temp_offset", "wired_humidity_offset",
)


def validate_calibration(values):
    """Validates a full set of calibration offsets for saving. `values`
    should have all six CALIBRATION_KEYS. Returns (cleaned_dict, None) on
    success or (None, error) on failure. Offsets are bounded to +/-20 -
    generous for genuine sensor calibration (a cheap sensor reading more
    than 20 degrees or 20%RH off is broken, not just uncalibrated) while
    still catching an obviously wrong entry (a stray extra digit, a
    misplaced decimal point) before it quietly corrupts every reading
    from that sensor."""
    cleaned = {}
    for key in CALIBRATION_KEYS:
        try:
            v = float(values.get(key, 0.0))
        except (TypeError, ValueError):
            return None, f"{key} must be a number"
        if not (-20 <= v <= 20):
            return None, f"{key} must be between -20 and 20"
        cleaned[key] = v
    return cleaned, None


def _atomic_write(path, data_str):
    tmp_path = path + ".tmp"
    with open(tmp_path, "w") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        f.write(data_str)
        f.flush()
        os.fsync(f.fileno())
        fcntl.flock(f, fcntl.LOCK_UN)
    os.replace(tmp_path, path)


def atomic_write_bytes(path, data_bytes):
    """Same write-tmp-then-rename pattern as _atomic_write, for binary
    data. Public (no leading underscore) since it's meant to be used
    from a different module, unlike the JSON-specific version above.
    [2026-09-14] Currently unused - its one caller (camera_service.py's
    old live-frame write to CAMERA_LIVE_PATH, one file every process
    shared and could race on) went away when live view switched to
    camera-streamer, which serves frames itself rather than writing them
    to a shared path (see docs/camera-streamer-setup.md). Left in place
    as a ready-to-use utility rather than deleted - the race it guards
    against is a real one for any future single-shared-file writer."""
    tmp_path = path + ".tmp"
    with open(tmp_path, "wb") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        f.write(data_bytes)
        f.flush()
        os.fsync(f.fileno())
        fcntl.flock(f, fcntl.LOCK_UN)
    os.replace(tmp_path, path)


def load_config():
    if not os.path.exists(CONFIG_PATH):
        save_config(DEFAULT_CONFIG)
        return json.loads(json.dumps(DEFAULT_CONFIG))
    with open(CONFIG_PATH, "r") as f:
        fcntl.flock(f, fcntl.LOCK_SH)
        try:
            data = json.load(f)
        finally:
            fcntl.flock(f, fcntl.LOCK_UN)
    # One-time migration from the old SensorPush-specific key names to
    # the new brand-agnostic ones (sensorpush_mac -> ble_mac,
    # sensorpush_*_offset -> ble_*_offset). Without this, upgrading past
    # that rename would silently reset an already-configured MAC address
    # and calibration offsets back to their defaults on the very next
    # load - the data wouldn't actually be gone, just sitting under a
    # key nothing reads anymore. Naturally completes itself on the next
    # save (of anything), since it rewrites `data` in place before the
    # merge below.
    if "sensorpush_mac" in data and "ble_mac" not in data:
        data["ble_mac"] = data.pop("sensorpush_mac")
    if "calibration" in data:
        cal = data["calibration"]
        if "sensorpush_temp_offset" in cal and "ble_temp_offset" not in cal:
            cal["ble_temp_offset"] = cal.pop("sensorpush_temp_offset")
        if "sensorpush_humidity_offset" in cal and "ble_humidity_offset" not in cal:
            cal["ble_humidity_offset"] = cal.pop("sensorpush_humidity_offset")
    # Same idea, for the camera interval settings' seconds -> fps unit
    # change: a VALUE conversion, not just a key rename, so a plain
    # backfill (below) can't do this on its own - an old config.json
    # missing live_capture_fps would otherwise silently fall back to the
    # DEFAULT_CONFIG fps value instead of preserving whatever rate was
    # actually configured under the old key.
    if "camera" in data:
        cam = data["camera"]
        if "live_capture_interval_seconds" in cam and "live_capture_fps" not in cam:
            old_interval = cam.pop("live_capture_interval_seconds")
            try:
                cam["live_capture_fps"] = round(1.0 / float(old_interval), 2)
            except (TypeError, ValueError, ZeroDivisionError):
                pass  # leave it out - the backfill below fills in the default
        if "stream_relay_interval_seconds" in cam and "stream_relay_fps" not in cam:
            old_interval = cam.pop("stream_relay_interval_seconds")
            try:
                cam["stream_relay_fps"] = round(1.0 / float(old_interval), 2)
            except (TypeError, ValueError, ZeroDivisionError):
                pass
    # Backfill any keys/modes added in later versions of this script so
    # an old config.json on disk doesn't crash a newer climate.py.
    merged = json.loads(json.dumps(DEFAULT_CONFIG))
    merged.update({k: v for k, v in data.items() if k not in ("modes", "calibration", "camera")})
    for mode_name, defaults in DEFAULT_CONFIG["modes"].items():
        merged["modes"][mode_name] = {**defaults, **data.get("modes", {}).get(mode_name, {})}
    merged["calibration"] = {**DEFAULT_CONFIG["calibration"], **data.get("calibration", {})}
    # Shallow-merged like calibration above (not replaced outright like
    # most top-level keys) so a config.json from before this field
    # existed - or one that only ever saved a subset of camera keys -
    # still backfills whichever camera settings it's missing from
    # DEFAULT_CONFIG, rather than silently losing them.
    merged["camera"] = {**DEFAULT_CONFIG["camera"], **data.get("camera", {})}
    # Three levels deep (notifications -> categories/quiet_hours/channels
    # -> individual keys), so a plain shallow merge like camera/calibration
    # above would silently drop a whole nested dict backfill (e.g. an old
    # config.json with no "notifications" key at all would merge in an
    # empty "categories": {} instead of every category defaulting to
    # visible/on). _merge_notifications below does the same "keep
    # whatever's on disk, backfill whatever's missing" merge one level
    # deeper.
    merged["notifications"] = _merge_notifications(
        DEFAULT_CONFIG["notifications"], data.get("notifications", {})
    )
    return merged


def _merge_notifications(defaults, saved):
    """Backfills a saved "notifications" block against DEFAULT_CONFIG's,
    one level deeper than the shallow {**defaults, **saved} pattern used
    for camera/calibration above - notifications nests dicts inside
    dicts (categories, quiet_hours, channels.pushover, channels.email,
    channels.webhook), and a shallow merge would replace e.g. the whole
    "categories" dict wholesale the moment a saved config has ANY
    categories key at all, silently losing every category added in a
    later version rather than defaulting it to on/off like everything
    else in this file does for a config.json from before it existed."""
    merged = {**defaults, **saved}
    merged["categories"] = {**defaults["categories"], **saved.get("categories", {})}
    merged["quiet_hours"] = {**defaults["quiet_hours"], **saved.get("quiet_hours", {})}
    saved_channels = saved.get("channels", {})
    merged["channels"] = {
        name: {**chan_defaults, **saved_channels.get(name, {})}
        for name, chan_defaults in defaults["channels"].items()
    }
    return merged


def save_config(config):
    _atomic_write(CONFIG_PATH, json.dumps(config, indent=2))


def validate_setpoints(mode, values):
    """Validate setpoint values coming from the web UI.
    Returns (cleaned_dict, None) on success or (None, error_message) on failure.
    """
    if mode not in VALID_MODES:
        return None, f"Unknown mode '{mode}'"
    try:
        low = float(values["low_temp_f"])
        high = float(values["high_temp_f"])
        humidity = float(values["humidity_setpoint"])
    except (KeyError, TypeError, ValueError):
        return None, "low_temp_f, high_temp_f and humidity_setpoint are required numbers"

    if not (TEMP_BOUNDS_F[0] <= low <= TEMP_BOUNDS_F[1]):
        return None, f"low_temp_f must be between {TEMP_BOUNDS_F[0]} and {TEMP_BOUNDS_F[1]}"
    if not (TEMP_BOUNDS_F[0] <= high <= TEMP_BOUNDS_F[1]):
        return None, f"high_temp_f must be between {TEMP_BOUNDS_F[0]} and {TEMP_BOUNDS_F[1]}"
    if low >= high:
        return None, "low_temp_f must be less than high_temp_f"
    if not (HUMIDITY_BOUNDS[0] <= humidity <= HUMIDITY_BOUNDS[1]):
        return None, f"humidity_setpoint must be between {HUMIDITY_BOUNDS[0]} and {HUMIDITY_BOUNDS[1]}"

    cleaned = {"low_temp_f": low, "high_temp_f": high, "humidity_setpoint": humidity}

    if mode == "cleaning":
        try:
            interval = int(values.get("vent_interval_minutes", 30))
            duration = int(values.get("vent_duration_minutes", 5))
        except (TypeError, ValueError):
            return None, "vent_interval_minutes and vent_duration_minutes must be integers"
        if not (VENT_INTERVAL_BOUNDS[0] <= interval <= VENT_INTERVAL_BOUNDS[1]):
            return None, (f"vent_interval_minutes must be between "
                           f"{VENT_INTERVAL_BOUNDS[0]} and {VENT_INTERVAL_BOUNDS[1]}")
        if not (VENT_DURATION_BOUNDS[0] <= duration <= VENT_DURATION_BOUNDS[1]):
            return None, (f"vent_duration_minutes must be between "
                           f"{VENT_DURATION_BOUNDS[0]} and {VENT_DURATION_BOUNDS[1]}")
        if duration >= interval:
            return None, "vent_duration_minutes should be shorter than vent_interval_minutes"
        cleaned["vent_interval_minutes"] = interval
        cleaned["vent_duration_minutes"] = duration

    # Timelapse cadence applies to every mode, not just cleaning - 0 is
    # the "never" sentinel and is deliberately exempt from
    # SNAPSHOT_INTERVAL_BOUNDS (which only constrains the non-zero case).
    try:
        snapshot_interval = int(values.get("snapshot_interval_minutes", 0))
    except (TypeError, ValueError):
        return None, "snapshot_interval_minutes must be a whole number"
    if snapshot_interval != 0 and not (SNAPSHOT_INTERVAL_BOUNDS[0] <= snapshot_interval <= SNAPSHOT_INTERVAL_BOUNDS[1]):
        return None, (f"snapshot_interval_minutes must be 0 (never) or between "
                       f"{SNAPSHOT_INTERVAL_BOUNDS[0]} and {SNAPSHOT_INTERVAL_BOUNDS[1]}")
    cleaned["snapshot_interval_minutes"] = snapshot_interval

    return cleaned, None


